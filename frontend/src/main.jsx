const API_URL = import.meta.env.VITE_API_URL || "http://localhost:5000/api";
const fields = [
  ["student_id", "Student ID", "Identifier for this projection", "text", undefined, undefined],
  ["study_hours_per_week", "Study hours / week", "Between 0 and 40 hours", "number", 0, 40],
  ["attendance_percentage", "Attendance", "Percentage from 0 to 100", "number", 0, 100],
  ["ca_marks_30", "CA marks", "Out of 30", "number", 0, 30],
  ["midterm_marks_25", "MTE marks", "Out of 25", "number", 0, 25],
];

const emptyForm = {
  student_id: "",
  study_hours_per_week: "",
  attendance_percentage: "",
  ca_marks_30: "",
  midterm_marks_25: "",
};

function scrollToId(id) {
  document.getElementById(id)?.scrollIntoView({ behavior: "smooth", block: "start" });
}

function App() {
  const [form, setForm] = useState(emptyForm);
  const [result, setResult] = useState(null);
  const [performance, setPerformance] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);
  const [performanceLoading, setPerformanceLoading] = useState(true);
  const [menuOpen, setMenuOpen] = useState(false);

  useEffect(() => {
    fetch(`${API_URL}/model-performance`)
      .then(async (response) => {
        const data = await response.json();
        if (!response.ok) throw new Error(data.error || "Evaluation data is unavailable.");
        setPerformance(data);
      })
      .catch((requestError) => setError(requestError.message))
      .finally(() => setPerformanceLoading(false));
  }, []);

  async function submit(event) {
    event.preventDefault();
    setError("");
    setLoading(true);
    try {
      const response = await fetch(`${API_URL}/predict`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(form),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "The prediction could not be completed.");
      setResult(data);
    } catch (requestError) {
      setError(requestError.message || "Unable to reach the Flask API.");
    } finally {
      setLoading(false);
    }
  }

  function navigate(id) {
    setMenuOpen(false);
    scrollToId(id);
  }

  return (
    <div className="site-shell">
      <header className="site-nav">
        <button className="wordmark" onClick={() => navigate("home")} aria-label="Go to home">
          <span className="wordmark-mark" aria-hidden="true"><span /><span /><span /></span>
          <span><strong>LPU</strong><small>Student Analytics</small></span>
        </button>
        <button className="mobile-menu" onClick={() => setMenuOpen(!menuOpen)} aria-expanded={menuOpen} aria-label="Toggle navigation">
          {menuOpen ? <X size={20} /> : <Menu size={20} />}
        </button>
        <nav className={`site-links ${menuOpen ? "open" : ""}`} aria-label="Primary navigation">
          <button onClick={() => navigate("home")}>Home</button>
          <button onClick={() => navigate("predictor")}>Predictor</button>
          <button onClick={() => navigate("insights")}>Model insights</button>
          <button onClick={() => navigate("how-it-works")}>How it works</button>
          <button className="nav-cta" onClick={() => navigate("predictor")}>Start a prediction <ArrowRight size={15} /></button>
        </nav>
      </header>

      <main>
        <section className="hero" id="home">
          <div className="hero-grid">
            <div className="hero-copy">
              <p className="eyebrow light">LPU STUDENT ANALYTICS <span>·</span> MACHINE LEARNING</p>
              <h1>Understand your performance <em>before it happens.</em></h1>
              <p className="hero-description">Predict endterm performance, understand your passing requirements, and turn academic data into clearer insights.</p>
              <div className="hero-actions">
                <button className="button button-primary" onClick={() => navigate("predictor")}>Predict a student <ArrowRight size={17} /></button>
                <button className="button button-quiet" onClick={() => navigate("insights")}>Explore model insights <ArrowDown size={16} /></button>
              </div>
              <p className="trust-note"><ShieldCheck size={15} /> Estimates are generated by trained models and are not official university grades.</p>
            </div>
            <HeroVisual
              onApplyScenario={(scenario) => {
                setForm({
                  student_id: `1232${Math.floor(1000 + Math.random() * 9000)}`,
                  study_hours_per_week: scenario.studyHours,
                  attendance_percentage: scenario.attendance,
                  ca_marks_30: scenario.ca,
                  midterm_marks_25: scenario.mte,
                });
                scrollToId("predictor");
              }}
            />
          </div>
          <div className="hero-footer"><span>Prediction workspace / 01</span><span>Built for clearer decisions before the endterm</span></div>
        </section>

        <section className="predictor-section" id="predictor">
          <div className="section-intro">
            <p className="eyebrow">LIVE PREDICTION WORKSPACE</p>
            <h2>Your next result starts here.</h2>
            <p>Enter a student's current academic profile to estimate ETE marks and understand the minimum score needed to pass.</p>
          </div>
          {error && <div className="alert" role="alert"><CircleAlert size={18} /> <span>{error}</span></div>}
          <div className="predictor-layout">
            <form className="input-panel" onSubmit={submit}>
              <div className="panel-title"><span>01</span><div><h3>Academic inputs</h3><p>Current profile, before the final examination.</p></div></div>
              <div className="form-grid">
                {fields.map(([name, label, hint, type, min, max]) => (
                  <label key={name} className={name === "student_id" ? "wide-field" : ""}>
                    <span>{label}</span>
                    <input
                      required
                      name={name}
                      type={type}
                      min={min}
                      max={max}
                      step={type === "number" ? "any" : undefined}
                      value={form[name]}
                      onChange={(event) => setForm((current) => ({ ...current, [name]: event.target.value }))}
                      placeholder={name === "student_id" ? "e.g. 12324751" : "0"}
                      aria-describedby={`${name}-hint`}
                    />
                    <small id={`${name}-hint`}>{hint}</small>
                  </label>
                ))}
              </div>
              <button className="button button-dark submit-button" disabled={loading}>
                {loading ? <><RefreshCw className="spin" size={17} /> Calculating...</> : <>Predict performance <ArrowRight size={17} /></>}
              </button>
              <p className="form-note">The model uses study habits, attendance, CA, and MTE. No ETE score is entered.</p>
            </form>
            {result ? <Results result={result} /> : <EmptyResults />}
          </div>
        </section>

        <section className="insights-section" id="insights">
          <div className="section-intro section-intro-dark">
            <p className="eyebrow">MODEL EVALUATION / HELD-OUT TEST DATA</p>
            <h2>Behind every prediction, a model you can inspect.</h2>
            <p>These are real evaluation artifacts from the trained models, measured on records they did not see during training.</p>
          </div>
          {performanceLoading ? <LoadingState /> : performance ? <Performance performance={performance} /> : <div className="honest-empty">Evaluation artifacts are not available. Run <code>python main.py</code> to train the models.</div>}
        </section>

        <section className="how-section" id="how-it-works">
          <div className="section-intro">
            <p className="eyebrow">THE WORKFLOW</p>
            <h2>From current marks to a clearer next move.</h2>
          </div>
          <div className="workflow">
            {[
              ["01", "Enter the profile", "Add the student's study hours, attendance, CA, and MTE marks."],
              ["02", "Estimate ETE marks", "The trained regression model estimates the endterm score out of 45."],
              ["03", "Calculate the threshold", "The app projects the total and works out the minimum ETE needed."],
              ["04", "Read two signals", "A separate classifier estimates Pass / Fail so both model readouts stay visible."],
            ].map(([number, title, copy]) => <div className="workflow-item" key={number}><span>{number}</span><h3>{title}</h3><p>{copy}</p></div>)}
          </div>
          <div className="disclaimer"><Sparkles size={17} /><p>Predictions are estimates for planning and reflection — never guaranteed outcomes or official university grades.</p></div>
        </section>
      </main>
      <footer className="site-footer"><span>LPU / Student Analytics</span><span>Academic prediction, made legible.</span></footer>
    </div>
  );
}

