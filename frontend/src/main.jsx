function EmptyResults() {
  return <div className="results-empty"><div className="empty-mark"><span /><span /><span /></div><h3>Your projection will appear here.</h3><p>Enter the pre-ETE profile to see the estimate, the deterministic pass check, and the minimum ETE calculator.</p><span className="empty-arrow"><ArrowDown size={15} /> waiting for student profile</span></div>;
}

function Results({ result }) {
  const pass = result.regression_projected_status === "Pass";
  const calculator = result.calculator || {};
  const predicted = Number(result.predicted_ete_marks);
  const required = Number(result.minimum_ete_marks);
  const predictedPercent = Math.min(100, Math.max(0, predicted / 45 * 100));
  const requiredPercent = Math.min(100, Math.max(0, required / 45 * 100));
  return <div className="results-panel">
    <div className={`result-status ${pass ? "is-pass" : "is-fail"}`}><div><span className="eyebrow">REGRESSION-BASED PROJECTED OUTCOME</span><h3>{pass ? "Projected pass" : "Projected fail"}</h3></div>{pass ? <CheckCircle2 size={26} /> : <CircleAlert size={26} />}</div>
    <div className="result-metrics"><ResultMetric label="Predicted ETE" value={`${predicted.toFixed(1)}/45`} /><ResultMetric label="Predicted total" value={`${Number(result.predicted_total_marks).toFixed(1)}/100`} /><ResultMetric label="ETE difference" value={`${Number(result.ete_gap) >= 0 ? "+" : ""}${Number(result.ete_gap).toFixed(1)}`} /></div>
    <div className="threshold-card">
      <div className="threshold-heading"><div><span className="eyebrow">SIGNATURE CALCULATOR</span><h3>What do you need in the final?</h3></div><span className={`possibility ${calculator.passing_possible ? "possible" : "impossible"}`}>{calculator.passing_possible ? "Possible" : "Impossible"}</span></div>
      <p className="threshold-lead">{calculator.passing_possible ? "Your minimum target is set by the stricter of the two passing conditions." : "Even a perfect 45/45 ETE cannot bring the projected total to 40/100."}</p>
      <div className="comparison"><div className="comparison-scale"><span>0</span><span>45 ETE maximum</span></div><div className="comparison-track"><span className="required-fill" style={{ width: `${requiredPercent}%` }} /><span className="predicted-marker" style={{ left: `${predictedPercent}%` }}><b>{predicted.toFixed(1)}</b></span><span className="required-marker" style={{ left: `${requiredPercent}%` }} /></div><div className="comparison-legend"><span><i className="legend-dot predicted-dot" /> Predicted ETE <b>{predicted.toFixed(1)}</b></span><span><i className="legend-dot required-dot" /> Minimum needed <b>{required.toFixed(1)}{Number.isInteger(required) ? "" : " / 14 whole-number"}</b></span></div></div>
      <div className="rule-list"><span><Check size={14} /> Overall passing threshold <b>40/100</b></span><span><Check size={14} /> ETE passing threshold <b>13.5/45</b> <small>(14 whole-number marks)</small></span><span className={pass ? "rule-pass" : "rule-fail"}>{pass ? <CheckCircle2 size={14} /> : <CircleAlert size={14} />} Meets both passing conditions: <b>{pass ? "Yes" : "Not yet"}</b></span></div>
    </div>
    <div className="model-readout"><div><span className="eyebrow">RULE-CONSISTENT MODEL READOUTS</span><p>Both displayed projections follow the same ETE estimate and passing rules.</p></div><span>Regression projection <Status status={result.regression_projected_status} /><small>Predicted ETE + exact passing rules</small></span><span>Classifier projection <Status status={result.classifier_projected_status} /><small>Rule-consistent display</small></span></div>
    <p className="mismatch"><CircleAlert size={15} /> The underlying classifier is retained for evaluation, but its raw historical signal is not used to override the mathematically calculated projected outcome.</p>
  </div>;
}

function ResultMetric({ label, value }) { return <div><span>{label}</span><strong>{value}</strong></div>; }
function Status({ status }) { return <b className={`status ${String(status).toLowerCase()}`}>{status}</b>; }

function Performance({ performance }) {
  const regression = performance.regression;
  const classification = performance.classification;
  return <div className="performance-content">
    <div className="evaluation-metrics"><ResultMetric label="Regression R²" value={regression.r2_score.toFixed(3)} /><ResultMetric label="Regression MAE" value={`${regression.mean_absolute_error.toFixed(2)} marks`} /><ResultMetric label="Classifier accuracy" value={classification.skipped ? "—" : classification.accuracy.toFixed(3)} /><ResultMetric label="Classifier F1" value={classification.skipped ? "—" : classification.f1_score.toFixed(3)} /></div>
    <div className="chart-grid">
      <figure className="chart-figure"><figcaption><span>REGRESSION / ETE MARKS</span><h3>Actual versus predicted</h3><p>Held-out test records show how closely the regression model tracks real ETE outcomes.</p></figcaption><img src={`${API_URL}/charts/actual_vs_predicted.png`} alt="Actual versus predicted ETE marks chart" /></figure>
      <figure className="chart-figure"><figcaption><span>CLASSIFICATION / PASS-FAIL</span><h3>Confusion matrix</h3><p>Accuracy, precision, recall, and F1-score keep the classifier's behavior inspectable.</p></figcaption>{classification.skipped ? <div className="honest-empty">Classification was skipped: {classification.reason}</div> : <img src={`${API_URL}/charts/confusion_matrix.png`} alt="Pass fail confusion matrix" />}</figure>
      <figure className="chart-figure feature-figure"><figcaption><span>FEATURE ANALYSIS</span><h3>What the model weighs</h3><p>Feature analysis from the trained classifier, not a decorative estimate.</p></figcaption><img src={`${API_URL}/charts/feature_analysis.png`} alt="Feature importance analysis chart" /></figure>
    </div>
    <p className="evaluation-footnote">Train/test split: {regression.train_size} training records and {regression.test_size} held-out records. Metrics describe model performance, not an individual student's certainty.</p>
  </div>;
}

function LoadingState() {
  return <div className="honest-empty"><RefreshCw className="spin" size={18} /> Loading saved evaluation artifacts...</div>;
}

